def num(x):
    try:
        return float(str(x).replace(",", "."))
    except Exception:
        return 0.0


def clean(h):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", h or "")).strip()


def load():
    rows = list(csv.DictReader(open(CSV, encoding="utf-8-sig"), delimiter=";"))
    seen = {}
    for r in rows:
        if num(r.get("Price")) > 0 and (r.get("Photo") or "").startswith("http"):
            u = (r.get("Url") or "").strip()
            if u and u not in seen:
                seen[u] = r
    return list(seen.values())


def key(url):
    return hashlib.md5(url.encode()).hexdigest()[:10]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--deck", required=True, choices=list(DECKS))
    a = ap.parse_args()

    title, kicker, chapters = DECKS[a.deck]
    lots = load()
    imgdir = os.path.join(OUT, f"img_{a.deck}")
    os.makedirs(imgdir, exist_ok=True)

    used, out_ch = set(), []
    for ch_name, ch_sub, picks in chapters:
        items = []
        for needle, n in picks:
            cand = [r for r in lots
                    if needle.lower() in r["Title"].lower() and r["Url"] not in used]
            cand.sort(key=lambda r: -num(r["Price"]))
            for r in cand[:n]:
                used.add(r["Url"])
                photos = [p for p in (r.get("Photo") or "").split() if p.startswith("http")]
                k = key(r["Url"])
                files = []
                for i, p in enumerate(photos[:3]):
                    dst = os.path.join(imgdir, f"{k}_{i}.jpg")
                    if not os.path.exists(dst):
                        try:
                            urllib.request.urlretrieve(p, dst)
                        except Exception as e:
                            print("  ! фото", p[:60], e, file=sys.stderr)
                            continue
                    files.append(os.path.relpath(dst, OUT))
                if not files:
                    continue
                items.append({
                    "key": k, "title": r["Title"], "price": int(num(r["Price"])),
                    "url": r["Url"], "photos": files,
                    "site_desc": clean(r.get("Description")),
                    "site_text": clean(r.get("Text"))[:1200],
                    "category": r.get("Category", ""),
                })
            if not cand:
                print(f"  · не найдено: {needle}", file=sys.stderr)
        if items:
            out_ch.append({"name": ch_name, "sub": ch_sub, "items": items})
            print(f"{ch_name:<26} {len(items)} лотов")

    man = {"deck": a.deck, "title": title, "kicker": kicker, "chapters": out_ch}
    path = os.path.join(OUT, f"manifest_{a.deck}.json")
    json.dump(man, open(path, "w"), ensure_ascii=False, indent=1)
    tot = sum(len(c["items"]) for c in out_ch)
    print(f"\n→ {path}: {tot} лотов, {len(out_ch)} глав, фото в img_{a.deck}/")


if __name__ == "__main__":
    main()
