def cert_map(c):
    c = (c or '').strip()
    if c.startswith('PSA'):
        return 'PSA/DNA'
    if c == 'JSA':
        return 'JSA'
    if c.startswith('Fanatics'):
        return ''
    if 'Beckett' in c or c == 'BAS' or c == 'Beckett BAS':
        return 'Beckett'
    return ''

